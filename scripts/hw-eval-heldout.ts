// Phase 1c, task 3: the fresh held-out set for the strict-marking profiles. Selects from a mutation DRAFT
// (scripts/hw-eval-mutate.ts generate) with a fixed rule that was written before any marking result existed:
//
//   per question: the original; the first two wrong_fact variants (in key-point order); the first remove_point; the first
//   paraphrase; every hindi_spelling_variant; and, for every second question in file order, its injection variant.
//
// The set is written as an immutable dataset version and labelled NOT PERSON-CHECKED (a note beside the manifest).
//
//   npm run hw:eval:heldout -- --draft ../../hw-evals/heldout-1c/draft --dataset heldout-1c@v1 [--datasets-root ../../hw-evals/datasets]

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

function arg(name: string, fallback?: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 ? process.argv[i + 1] : fallback;
}

async function main() {
  const { parseManifest, writeDatasetVersion } = await import('@/lib/hw/eval/dataset');
  type EvalItem = import('@/lib/hw/eval/dataset').EvalItem;
  const parsed = parseManifest(readFileSync(join(arg('draft')!, 'items.jsonl'), 'utf8'));
  if ('problems' in parsed) throw new Error(parsed.problems.join('\n'));
  const byQ = new Map<string, EvalItem[]>();
  for (const it of parsed.items) byQ.set(it.question.id, [...(byQ.get(it.question.id) ?? []), it]);

  const keep: EvalItem[] = [];
  [...byQ.values()].forEach((items, qi) => {
    const of = (t: string) => items.filter((i) => i.mutation?.type === t);
    const pointOrder = (i: EvalItem) => i.key!.points.findIndex((p) => p.id === i.mutation?.target);
    keep.push(...of('original'));
    keep.push(...of('wrong_fact').sort((a, b) => pointOrder(a) - pointOrder(b)).slice(0, 2));
    keep.push(...of('remove_point').sort((a, b) => pointOrder(a) - pointOrder(b)).slice(0, 1));
    keep.push(...of('paraphrase').slice(0, 1));
    keep.push(...of('hindi_spelling_variant'));
    if (qi % 2 === 0) keep.push(...of('injection').slice(0, 1));
  });
  const dir = writeDatasetVersion(arg('datasets-root', '../../hw-evals/datasets')!, arg('dataset')!, keep);
  writeFileSync(join(dir, 'NOT_PERSON_CHECKED.txt'), 'Generated by scripts/hw-eval-mutate.ts (mutator anthropic/claude-haiku-5.5). The variants and their expected marks have NOT been checked by a person.\n');
  const t: Record<string, number> = {};
  keep.forEach((i) => { t[i.mutation!.type] = (t[i.mutation!.type] ?? 0) + 1; });
  console.log(`${keep.length} items from ${byQ.size} questions written to ${dir}: ${JSON.stringify(t)}`);
}
main().catch((e) => { console.error(e instanceof Error ? e.message : e); process.exit(1); });
